package store

import (
	"context"
	"database/sql"
	"encoding/json"
	"errors"
	"fmt"
)

type NotificationActivityRef struct {
	ID       int64  `json:"id"`
	Revision int64  `json:"revision"`
	Ref      string `json:"ref"`
}
type NotificationDelta struct {
	Replay       bool                      `json:"replay,omitempty"`
	SourceID     string                    `json:"source_id"`
	SubjectURL   string                    `json:"subject_url"`
	ScanID       int64                     `json:"scan_id"`
	Since        string                    `json:"since,omitempty"`
	Complete     bool                      `json:"complete"`
	Activities   []NotificationActivityRef `json:"activities"`
	Fetched      int                       `json:"fetched"`
	Changed      int                       `json:"changed"`
	Unchanged    int                       `json:"unchanged"`
	FetchedBytes int                       `json:"fetched_bytes"`
}

// CommitNotificationActivitySnapshot shares the Inbox publication transaction.
// Only immutable versions in the frozen, completely retrieved manifest are
// acknowledged. Newer cached versions are deliberately left undecided.
func CommitNotificationActivitySnapshot(ctx context.Context, tx *sql.Tx, batchID string) error {
	var snapshot, result string
	if err := tx.QueryRowContext(ctx, `SELECT processor_snapshot,processor_result FROM notification_batches WHERE id=?`, batchID).Scan(&snapshot, &result); err != nil {
		return err
	}
	var bundle struct {
		Subjects []struct {
			EventIDs []int64 `json:"event_ids"`
			Source   struct {
				Delta *NotificationDelta `json:"activity_delta"`
			} `json:"source"`
		} `json:"subjects"`
	}
	if err := json.Unmarshal([]byte(snapshot), &bundle); err != nil {
		return err
	}
	var output struct {
		Decisions []struct {
			EventIDs     []int64  `json:"event_ids"`
			ActivityRefs []string `json:"activity_refs"`
		} `json:"decisions"`
	}
	if err := json.Unmarshal([]byte(result), &output); err != nil {
		return err
	}
	coverage := map[string]map[int64]bool{}
	for _, decision := range output.Decisions {
		for _, ref := range decision.ActivityRefs {
			if coverage[ref] != nil {
				return errors.New("activity version decided more than once")
			}
			coverage[ref] = map[int64]bool{}
			for _, id := range decision.EventIDs {
				coverage[ref][id] = true
			}
		}
	}
	for _, sub := range bundle.Subjects {
		d := sub.Source.Delta
		if d == nil {
			continue
		}
		if !d.Complete {
			return errors.New("cannot publish incomplete notification activity")
		}
		// The scan receipt is generated by retrieval, never by the model.
		var complete bool
		var manifest, started string
		if err := tx.QueryRowContext(ctx, `SELECT complete,manifest,started_at FROM notification_activity_scans WHERE id=? AND source_id=? AND subject_url=?`, d.ScanID, d.SourceID, d.SubjectURL).Scan(&complete, &manifest, &started); err != nil {
			return err
		}
		expected, _ := json.Marshal(d.Activities)
		if !complete || manifest != string(expected) {
			return errors.New("notification activity manifest changed")
		}
		for _, id := range sub.EventIDs {
			var source, url string
			if err := tx.QueryRowContext(ctx, `SELECT source_id,json_extract(payload,'$.url') FROM notification_events WHERE id=? AND id IN (SELECT event_id FROM notification_batch_events WHERE batch_id=?)`, id, batchID).Scan(&source, &url); err != nil {
				return err
			}
			if source != d.SourceID || url != d.SubjectURL {
				return errors.New("activity scan belongs to another notification")
			}
		}
		for _, ref := range d.Activities {
			bound := false
			for _, id := range sub.EventIDs {
				bound = bound || coverage[ref.Ref][id]
			}
			if !bound {
				return fmt.Errorf("undecided activity %s", ref.Ref)
			}
			if ref.Ref != fmt.Sprintf("A%d/V%d", ref.ID, ref.Revision) {
				return errors.New("invalid activity reference")
			}
			var exists int
			if err := tx.QueryRowContext(ctx, `SELECT count(*) FROM notification_activity_versions v JOIN notification_activities a ON a.id=v.activity_id WHERE a.id=? AND v.revision=? AND a.source_id=? AND a.subject_url=?`, ref.ID, ref.Revision, d.SourceID, d.SubjectURL).Scan(&exists); err != nil {
				return err
			}
			if exists != 1 {
				return errors.New("activity version is unavailable")
			}
			if _, err := tx.ExecContext(ctx, `UPDATE notification_activity_versions SET processed_batch_id=? WHERE activity_id=? AND revision<=? AND processed_batch_id IS NULL`, batchID, ref.ID, ref.Revision); err != nil {
				return err
			}
		}
		if _, err := tx.ExecContext(ctx, `UPDATE notification_activity_subjects SET processed_through=max(processed_through,?),repair_from='' WHERE source_id=? AND subject_url=?`, started, d.SourceID, d.SubjectURL); err != nil {
			return err
		}
		if _, err := tx.ExecContext(ctx, `UPDATE notification_activity_scans SET processed_batch_id=? WHERE id=?`, batchID, d.ScanID); err != nil {
			return err
		}
	}
	return nil
}
